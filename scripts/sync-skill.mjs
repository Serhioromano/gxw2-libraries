#!/usr/bin/env node
// Generates the skill's documentation, images, source code and source index from
// the library folders. The library folders are the single source of truth.
//
// Usage:
//   node scripts/sync-skill.mjs           regenerate the skill payload
//   node scripts/sync-skill.mjs --check   exit 1 if the payload is out of date

import { mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SKILL_DIR = path.join(ROOT, 'skills', 'gxw2-libraries');
const CHECK = process.argv.includes('--check');
const QUIET = process.argv.includes('--quiet');

// Library folder and its user documentation file.
const LIBRARIES = [
  { name: 'AlarmManager', doc: 'AlarmManager.md' },
  { name: 'ModbusDriver', doc: 'Modbus.md' },
  { name: 'TimeControl', doc: 'TimeControl.md' },
  { name: 'Utils', doc: 'Utils.md' },
];

// Include the old assets directory in stale-file checks so it is removed on sync.
const GENERATED_DIRS = ['references', 'assets'];

const PREFIX_KINDS = [
  ['FB_', 'Function block'],
  ['F_', 'Function'],
  ['PRG_', 'Program'],
  ['GVL_', 'Global label list'],
  ['ST_', 'Struct'],
];

/** Rewrites documentation image links to the per-library image folder. */
function rewriteImageLinks(text, library) {
  return text.replace(/\(\.\/img\//g, `(./img/${library}/`);
}

/**
 * Reads the curated one-line POU descriptions from a library AGENT.md
 * "File Structure" listing (lines such as `F_SCALE.iecst / .csv — Purpose`).
 * Falls back to nothing when the section is missing or formatted differently.
 */
function parseAgentSummaries(text) {
  const summaries = new Map();
  for (const line of text.split(/\r?\n/)) {
    const match =
      line.match(/^\s*[\u2502\u251c\u2514\u2500\s]*([A-Za-z0-9_]+)\.iecst\b[^\u2014\n]*\u2014\s*(.+?)\s*$/) ||
      line.match(/^\s*[\u2502\u251c\u2514\u2500\s]*([A-Za-z0-9_]+)\.csv\b[^\u2014\n]*\u2014\s*(.+?)\s*$/);
    if (match) summaries.set(match[1], match[2]);
  }
  return summaries;
}

/** Strips the redundant `Function:` / `Function Block:` prefix from a description. */
function cleanDescription(text) {
  return text
    .replace(/^(Function block|Function|Program):\s*/i, '')
    .trim()
    .replace(/\|/g, '\\|');
}

/** Returns the POU kind from its name prefix, or from the code when unprefixed. */
function pouKind(name, code, description = '') {
  for (const [prefix, kind] of PREFIX_KINDS) {
    if (name.startsWith(prefix)) return kind;
  }
  if (code && new RegExp(`^\\s*${name}\\s*:=`, 'm').test(code)) return 'Function';
  if (/^Function block:\s*/i.test(description)) return 'Function block';
  if (/^Function:\s*/i.test(description)) return 'Function';
  if (/^Program:\s*/i.test(description)) return 'Program';
  return 'Function block / program';
}

/**
 * Builds a one-line summary from the leading block comment of an ST source.
 * Returns an empty string when the file has no descriptive header.
 */
function summarizeSource(code, name) {
  const header = code.replace(/^\uFEFF/, '').match(/^\s*\(\*([\s\S]*?)\*\)/);
  if (!header) return '';
  const paragraph = header[1]
    .split(/\r?\n\s*\r?\n/)[0]
    .split(/\r?\n/)
    .map((line) => line.replace(/^\s*\*?\s*/, '').trim())
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (!paragraph) return '';
  const sentenceEnd = paragraph.search(/[.!?](?=\s|$)/);
  // Skip header blocks that are tables or field descriptions, not a summary.
  if (sentenceEnd === -1 && !paragraph.includes(name)) return '';
  let summary = sentenceEnd === -1 ? paragraph : paragraph.slice(0, sentenceEnd + 1);
  if (summary.length > 150) summary = `${summary.slice(0, 147).trimEnd()}\u2026`;
  return summary.replace(/\|/g, '\\|');
}

/** Renders references/src/INDEX.md from the collected source rows. */
function renderSourceIndex(rows) {
  const lines = [
    '# Library Source Index',
    '',
    'Generated by `npm run sync-skill` from `libraries/<Library>/POU/`. Do not edit.',
    '',
    'The manuals (`references/<Library>.md`) are the primary reference. Use the',
    'sources only when a manual leaves a detail unclear: exact edge-case behaviour,',
    'undocumented parameters, declared variable types, device side effects, or a',
    'complete usage example (the `PRG_*_TEST` programs).',
    '',
    '`.iecst` is the Structured Text implementation; `.csv` is the GX Works 2 label',
    'list with inputs, outputs, in/out and local variables and their comments. Label',
    'copies here are converted from UTF-16 LE to UTF-8 for reading; the originals',
    'in `libraries/<Library>/POU/` are the files to import into GX Works 2.',
    '',
  ];
  for (const { library, entries } of rows) {
    lines.push(`## ${library}`, '');
    lines.push('| POU | Kind | Summary | Files |');
    lines.push('|---|---|---|---|');
    for (const entry of entries) {
      const files = [];
      if (entry.code) files.push(`[code](${library}/${entry.code})`);
      if (entry.labels) files.push(`[labels](${library}/${entry.labels})`);
      lines.push(
        `| \`${entry.name}\` | ${entry.kind} | ${entry.summary || '\u2014'} | ${files.join(' \u00b7 ')} |`,
      );
    }
    lines.push('');
  }
  return lines.join('\n');
}

async function listFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      for (const nested of await listFiles(full)) files.push(path.join(entry.name, nested));
    } else {
      files.push(entry.name);
    }
  }
  return files;
}

async function buildPlan() {
  const plan = [];
  const sourceRows = [];
  for (const { name, doc } of LIBRARIES) {
    const libDir = path.join(ROOT, 'libraries', name);
    if (!(await stat(libDir).catch(() => null))) {
      throw new Error(`Missing library folder: libraries/${name}`);
    }

    const docSrc = path.join(libDir, doc);
    const docText = await readFile(docSrc, 'utf8').catch(() => {
      throw new Error(`Missing documentation file: libraries/${name}/${doc}`);
    });
    plan.push({
      source: `libraries/${name}/${doc}`,
      target: `references/${name}.md`,
      content: Buffer.from(rewriteImageLinks(docText, name), 'utf8'),
    });

    const imgDir = path.join(libDir, 'img');
    for (const image of await listFiles(imgDir)) {
      plan.push({
        source: `libraries/${name}/img/${image}`,
        target: `references/img/${name}/${image}`,
        content: await readFile(path.join(imgDir, image)),
      });
    }

    // Source code and label lists, so the agent can verify details the manual omits.
    const pouDir = path.join(libDir, 'POU');
    const pouFiles = (await listFiles(pouDir)).sort();
    const agentText = await readFile(path.join(libDir, 'AGENT.md'), 'utf8').catch(() => '');
    const agentSummaries = parseAgentSummaries(agentText);
    const entries = new Map();
    for (const file of pouFiles) {
      const content = await readFile(path.join(pouDir, file));
      // Label files are UTF-16 LE; keep them readable in the skill copy.
      const payload = file.endsWith('.csv')
        ? Buffer.from(content.toString('utf16le').replace(/^\uFEFF/, ''), 'utf8')
        : content;
      plan.push({
        source: `libraries/${name}/POU/${file}`,
        target: `references/src/${name}/${file}`,
        content: payload,
      });
      const pouName = path.basename(file, path.extname(file));
      const entry = entries.get(pouName) ?? { name: pouName, kind: '', summary: '' };
      const agentDescription = agentSummaries.get(pouName) ?? '';
      if (file.endsWith('.iecst')) {
        const code = content.toString('utf8');
        entry.code = file;
        entry.summary = cleanDescription(agentDescription) || summarizeSource(code, pouName);
        entry.kind = pouKind(pouName, code, agentDescription);
      } else if (file.endsWith('.csv')) {
        entry.labels = file;
        entry.summary ||= cleanDescription(agentDescription);
        entry.kind ||= pouKind(pouName, '', agentDescription);
      }
      entries.set(pouName, entry);
    }
    sourceRows.push({ library: name, entries: [...entries.values()] });
  }
  plan.push({
    source: 'generated',
    target: 'references/src/INDEX.md',
    content: Buffer.from(renderSourceIndex(sourceRows), 'utf8'),
  });
  return plan;
}

async function main() {
  const plan = await buildPlan();
  const expected = new Set(plan.map((entry) => entry.target));
  const changed = [];
  const missing = [];

  for (const entry of plan) {
    const target = path.join(SKILL_DIR, entry.target);
    const current = await readFile(target).catch(() => null);
    if (!current) missing.push(entry.target);
    else if (!current.equals(entry.content)) changed.push(entry.target);
  }

  const stale = [];
  for (const dir of GENERATED_DIRS) {
    for (const file of await listFiles(path.join(SKILL_DIR, dir))) {
      const rel = `${dir}/${file.split(path.sep).join('/')}`;
      if (!expected.has(rel)) stale.push(rel);
    }
  }

  if (CHECK) {
    for (const file of missing) console.error(`missing   ${file}`);
    for (const file of changed) console.error(`outdated  ${file}`);
    for (const file of stale) console.error(`stale     ${file}`);
    if (missing.length || changed.length || stale.length) {
      console.error('\nSkill payload is out of date. Run: npm run sync-skill');
      process.exit(1);
    }
    console.log(`Skill payload is up to date (${plan.length} files).`);
    return;
  }

  for (const dir of GENERATED_DIRS) {
    await rm(path.join(SKILL_DIR, dir), { recursive: true, force: true });
  }
  for (const entry of plan) {
    const target = path.join(SKILL_DIR, entry.target);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, entry.content);
  }
  if (!QUIET) {
    console.log(
      `Skill payload synced: ${plan.length} files written, ` +
        `${changed.length} updated, ${missing.length} created, ${stale.length} removed.`,
    );
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
